package com.invotracker.invoice;
import com.invotracker.user.*;
import com.lowagie.text.*;
import com.lowagie.text.pdf.*;
import java.io.ByteArrayOutputStream;
import java.math.BigDecimal;
import java.util.List;
import org.springframework.http.*;
import org.springframework.security.core.Authentication;
import org.springframework.web.bind.annotation.*;
import org.springframework.web.server.ResponseStatusException;
@RestController @RequestMapping("/api/invoices")
public class InvoicePdfController {
 private final InvoiceRepository invoices;private final InvoiceLineItemRepository lines;private final AppUserRepository users;
 public InvoicePdfController(InvoiceRepository invoices,InvoiceLineItemRepository lines,AppUserRepository users){this.invoices=invoices;this.lines=lines;this.users=users;}
 @GetMapping(value="/{id}/pdf",produces="application/pdf")
 public ResponseEntity<byte[]> pdf(@PathVariable Long id,Authentication auth){
  AppUser owner=users.findByEmailIgnoreCase(auth.getName()).orElseThrow(()->new ResponseStatusException(HttpStatus.UNAUTHORIZED));
  Invoice i=invoices.findByIdAndOwnerId(id,owner.getId()).orElseThrow(()->new ResponseStatusException(HttpStatus.NOT_FOUND));
  try {ByteArrayOutputStream bytes=new ByteArrayOutputStream();Document doc=new Document(PageSize.A4,40,40,48,48);PdfWriter.getInstance(doc,bytes);doc.open();
   Font title=new Font(Font.HELVETICA,20,Font.BOLD);Font bold=new Font(Font.HELVETICA,10,Font.BOLD);
   doc.add(new Paragraph(switch(i.getTemplateType()){case "GROCERY" -> "RETAIL BILL";case "FREELANCER" -> "SERVICE INVOICE";case "MANUFACTURING" -> "COMMERCIAL INVOICE";case "TRANSPORT" -> "TRANSPORT INVOICE";case "HEALTHCARE" -> "CLINIC INVOICE";default -> "INVOICE";},title));doc.add(new Paragraph(owner.getBusinessName()));doc.add(new Paragraph("Invoice: "+i.getInvoiceNumber()+"    Status: "+i.getStatus()));
   doc.add(new Paragraph("Customer: "+i.getCustomerName()));doc.add(new Paragraph("Customer GSTIN: "+(i.getCustomerGstin()==null?"N/A":i.getCustomerGstin())));
   doc.add(new Paragraph("Issued: "+i.getIssueDate()+"    Due: "+i.getDueDate()));doc.add(Chunk.NEWLINE);
   PdfPTable table=new PdfPTable(new float[]{4,1,2,2,2});table.setWidthPercentage(100);
   for(String h:new String[]{"Description","Qty","Rate (INR)","GST %","Taxable (INR)"}){PdfPCell cell=new PdfPCell(new Phrase(h,bold));cell.setPadding(7);table.addCell(cell);}
   List<InvoiceLineItem> items=lines.findAllByInvoiceIdOrderByIdAsc(id);
   if(items.isEmpty()){for(String x:new String[]{"Legacy invoice (no item breakdown)","1",i.getTaxableAmount().toString(),i.getGstRate().toString(),i.getTaxableAmount().toString()})table.addCell(x);}
   else for(InvoiceLineItem line:items){table.addCell(line.getDescription());table.addCell(line.getQuantity().toPlainString());table.addCell(line.getUnitPrice().toPlainString());table.addCell(line.getGstRate().toPlainString());table.addCell(line.getLineTotal().toPlainString());}
   doc.add(table);doc.add(Chunk.NEWLINE);
   doc.add(new Paragraph("Taxable amount: INR "+i.getTaxableAmount()));
   BigDecimal tax=i.getTotalAmount().subtract(i.getTaxableAmount());doc.add(new Paragraph("GST total: INR "+tax));
   doc.add(new Paragraph("TOTAL: INR "+i.getTotalAmount(),bold));doc.add(new Paragraph("Paid: INR "+i.getPaidAmount()+"    Balance: INR "+i.getBalance()));
   doc.add(Chunk.NEWLINE);doc.add(new Paragraph("Generated by InvoTracker. Please verify tax details before filing."));doc.close();
   return ResponseEntity.ok().header(HttpHeaders.CONTENT_DISPOSITION,"attachment; filename=invoice-"+id+".pdf").contentType(MediaType.APPLICATION_PDF).body(bytes.toByteArray());
  }catch(DocumentException e){throw new ResponseStatusException(HttpStatus.INTERNAL_SERVER_ERROR,"Could not generate PDF",e);}
 }
}
